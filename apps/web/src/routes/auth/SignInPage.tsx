import React, { useState } from 'react';
import { useNavigate } from '@tanstack/react-router';
import { Card, CardHeader, CardTitle, CardContent, Button, Input } from '@idmis/ui';
import { useAuth } from '../../auth';

export function SignInPage() {
  const navigate = useNavigate();
  const { signIn, verifyTotp } = useAuth();

  const [email, setEmail] = useState('admin@idmis.gov.ng');
  const [password, setPassword] = useState('AdminSecret123!');
  const [tempToken, setTempToken] = useState<string | null>(null);
  const [totpCode, setTotpCode] = useState('');
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setError(null);
    setLoading(true);

    try {
      if (tempToken) {
        // Step 2: TOTP Verification
        const res = await verifyTotp({
          tempToken,
          totpCode,
        });
        if (res.status === 'authenticated') {
          navigate({ to: '/' });
        }
      } else {
        // Step 1: Sign In
        const res = await signIn({
          email,
          password,
        });

        if (res.status === 'authenticated') {
          navigate({ to: '/' });
        } else if (res.status === 'totp_required') {
          setTempToken(res.tempToken);
        } else if (res.status === 'password_change_required') {
          setError('Password reset is required. Please contact administrator.');
        } else {
          setError('Two-factor setup is required. Please check your authenticator.');
        }
      }
    } catch (err: unknown) {
      if (err instanceof Error) {
        setError(err.message);
      } else {
        setError('Sign-in failed. Please check your credentials.');
      }
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="min-h-screen bg-slate-50 flex flex-col justify-center items-center p-4">
      <div className="w-full max-w-md">
        <div className="text-center mb-8">
          <div className="inline-flex items-center justify-center w-12 h-12 rounded-xl bg-teal-700 text-white font-bold text-xl mb-3 shadow-md">
            ID
          </div>
          <h1 className="text-2xl font-bold tracking-tight text-slate-900">TRIMING IDMIS 2.0</h1>
          <p className="text-sm text-slate-500 mt-1">
            Irrigation Department Management Information System
          </p>
        </div>

        <Card className="shadow-lg border-slate-200">
          <CardHeader>
            <CardTitle className="text-xl">
              {tempToken ? 'Two-Factor Authentication' : 'Sign in to your account'}
            </CardTitle>
            <p className="text-xs text-slate-500 mt-1">
              {tempToken
                ? 'Enter the 6-digit authentication code generated by your TOTP app.'
                : 'Enter your official TRIMING / FMWR credentials.'}
            </p>
          </CardHeader>
          <CardContent>
            {error && (
              <div
                role="alert"
                className="mb-4 p-3 bg-red-50 border border-red-200 rounded-md text-sm text-red-700"
              >
                {error}
              </div>
            )}

            <form onSubmit={handleSubmit} className="space-y-4">
              {!tempToken ? (
                <>
                  <div className="space-y-1">
                    <label
                      htmlFor="signin-email"
                      className="block text-xs font-semibold uppercase tracking-wider text-slate-600"
                    >
                      Email address
                    </label>
                    <Input
                      id="signin-email"
                      type="email"
                      required
                      value={email}
                      onChange={(e) => setEmail(e.target.value)}
                      placeholder="user@idmis.gov.ng"
                      className="w-full"
                    />
                  </div>

                  <div className="space-y-1">
                    <label
                      htmlFor="signin-password"
                      className="block text-xs font-semibold uppercase tracking-wider text-slate-600"
                    >
                      Password
                    </label>
                    <Input
                      id="signin-password"
                      type="password"
                      required
                      value={password}
                      onChange={(e) => setPassword(e.target.value)}
                      placeholder="••••••••••••"
                      className="w-full"
                    />
                  </div>
                </>
              ) : (
                <div className="space-y-1">
                  <label
                    htmlFor="signin-totp"
                    className="block text-xs font-semibold uppercase tracking-wider text-slate-600"
                  >
                    6-Digit Verification Code
                  </label>
                  <Input
                    id="signin-totp"
                    type="text"
                    required
                    maxLength={6}
                    pattern="\d{6}"
                    value={totpCode}
                    onChange={(e) => setTotpCode(e.target.value)}
                    placeholder="123456"
                    className="w-full text-center text-lg tracking-widest font-mono"
                    autoFocus
                  />
                  <p className="text-xs text-slate-400 mt-1">
                    Tip: in test mode, the mock code is{' '}
                    <span className="font-mono font-semibold">123456</span>
                  </p>
                </div>
              )}

              <Button type="submit" disabled={loading} className="w-full mt-2">
                {loading ? 'Verifying...' : tempToken ? 'Verify & Sign In' : 'Sign In'}
              </Button>

              {tempToken && (
                <Button
                  type="button"
                  variant="outline"
                  onClick={() => {
                    setTempToken(null);
                    setTotpCode('');
                    setError(null);
                  }}
                  className="w-full"
                >
                  Back to Sign In
                </Button>
              )}
            </form>
          </CardContent>
        </Card>

        <p className="text-center text-xs text-slate-400 mt-6">
          Federal Ministry of Water Resources and Sanitation — TRIMING Project
        </p>
      </div>
    </div>
  );
}
