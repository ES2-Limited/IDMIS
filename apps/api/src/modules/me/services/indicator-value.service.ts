import {
  Injectable,
  NotFoundException,
  ForbiddenException,
  BadRequestException,
} from '@nestjs/common';
import { permissions } from '@idmis/contracts';
import type {
  CreateIndicatorValueInput,
  UpdateIndicatorValueInput,
  SubmitIndicatorValueInput,
  ApproveIndicatorValueInput,
  ReturnIndicatorValueInput,
  AttachEvidenceInput,
  ListIndicatorValuesQuery,
} from '@idmis/contracts';
import type { UserAuthz } from '../../../platform/auth';
import { runInTransaction } from '../../../platform/database/transaction.helper';
import { ConflictProblemException } from '../../../platform/filters';
import { FileRepository } from '../../core/public';
import { IndicatorValueRepository } from '../repositories/indicator-value.repository';
import { IndicatorRepository } from '../repositories/indicator.repository';
import { assertMeScope } from '../utils/assert-me-scope';

@Injectable()
export class IndicatorValueService {
  constructor(
    private readonly valueRepo: IndicatorValueRepository,
    private readonly indicatorRepo: IndicatorRepository,
    private readonly fileRepo: FileRepository,
  ) {}

  async listValues(query: ListIndicatorValuesQuery, authz: UserAuthz) {
    const scope = authz.scopeFor(permissions.ME_INDICATOR_READ);
    return this.valueRepo.listValues(scope, query);
  }

  async getValue(id: string, authz: UserAuthz) {
    const scope = authz.scopeFor(permissions.ME_INDICATOR_READ);
    const value = await this.valueRepo.findById(id, scope);
    if (!value) {
      throw new NotFoundException(`Indicator value with ID '${id}' not found`);
    }
    return value;
  }

  async createValue(
    input: CreateIndicatorValueInput,
    authz: UserAuthz,
    actorUserId: string,
    source: 'manual' | 'computed' | 'import' = 'manual',
    importBatchId?: string,
  ) {
    const ind = await this.indicatorRepo.findById(input.indicatorId);
    if (!ind) {
      throw new NotFoundException(`Indicator with ID '${input.indicatorId}' not found`);
    }

    if (ind.method === 'computed' && source !== 'computed') {
      throw new ConflictProblemException({
        detail:
          'Cannot manually record values for computed indicators. Computed indicators are generated by automated compute jobs.',
        current: null,
        currentVersion: 0,
      });
    }

    const resolvedScope = await assertMeScope(authz, permissions.ME_VALUE_SUBMIT, {
      scopeType: input.scopeType,
      scopeStateId: input.scopeStateId,
      scopeOrgId: input.scopeOrgId,
    });

    const existing = await this.valueRepo.findBySlot(
      input.indicatorId,
      input.periodYear,
      input.periodQuarter ?? null,
      resolvedScope.scopeType,
      resolvedScope.scopeStateId,
      resolvedScope.scopeOrgId,
      (input.disaggregation as Record<string, unknown>) ?? {},
    );

    if (existing) {
      throw new ConflictProblemException({
        detail: 'Value already exists for this slot (indicator, period, scope, disaggregation)',
        current: existing,
        currentVersion: existing.version,
      });
    }

    const isSubmitted = input.status === 'submitted' || source === 'import';
    const initialStatus = isSubmitted ? 'submitted' : 'draft';
    const submittedBy = isSubmitted ? actorUserId : null;
    const submittedAt = isSubmitted ? new Date().toISOString() : null;

    return runInTransaction(
      async (tx) => {
        const created = await this.valueRepo.create(
          {
            indicatorId: input.indicatorId,
            periodYear: input.periodYear,
            periodQuarter: input.periodQuarter ?? null,
            scopeType: resolvedScope.scopeType,
            scopeStateId: resolvedScope.scopeStateId,
            scopeOrgId: resolvedScope.scopeOrgId,
            disaggregation: (input.disaggregation as Record<string, unknown>) ?? {},
            value: input.value,
            source,
            notes: input.notes ?? null,
            status: initialStatus,
            submittedBy,
            submittedAt,
            importBatchId: importBatchId ?? null,
            createdBy: actorUserId,
          },
          tx,
        );

        return created;
      },
      {
        audit: {
          action: 'create',
          entity: 'me.indicator_value',
          actorUserId,
        },
      },
    );
  }

  async updateValue(
    id: string,
    input: UpdateIndicatorValueInput,
    authz: UserAuthz,
    actorUserId: string,
  ) {
    const existing = await this.valueRepo.findById(id);
    if (!existing) {
      throw new NotFoundException(`Indicator value with ID '${id}' not found`);
    }

    await assertMeScope(
      authz,
      permissions.ME_VALUE_SUBMIT,
      {
        scopeType: existing.scopeType,
        scopeStateId: existing.scopeStateId,
        scopeOrgId: existing.scopeOrgId,
      },
      true,
    );

    const ind = await this.indicatorRepo.findById(existing.indicatorId);
    if (ind && ind.method === 'computed') {
      throw new ConflictProblemException({
        detail: 'Cannot manually update values for computed indicators.',
        current: null,
        currentVersion: 0,
      });
    }

    if (existing.version !== input.version) {
      throw new ConflictProblemException({
        detail: 'Indicator value version mismatch. Record was modified by another user.',
        current: existing,
        currentVersion: existing.version,
      });
    }

    // Approved values are locked; changing one requires a new submission
    const isApproved = existing.status === 'approved';
    const nextStatus = isApproved ? 'submitted' : existing.status;
    const submittedBy = isApproved ? actorUserId : existing.submittedBy;
    const submittedAt = isApproved ? new Date().toISOString() : existing.submittedAt;

    return runInTransaction(
      async (tx) => {
        const updated = await this.valueRepo.update(
          id,
          input.version,
          {
            value: input.value,
            notes: input.notes,
            disaggregation: input.disaggregation as Record<string, unknown> | undefined,
            status: nextStatus,
            submittedBy,
            submittedAt,
            approvedBy: isApproved ? null : existing.approvedBy,
            approvedAt: isApproved ? null : existing.approvedAt,
            returnedBy: isApproved ? null : existing.returnedBy,
            returnedAt: isApproved ? null : existing.returnedAt,
            returnComment: isApproved ? null : existing.returnComment,
            updatedBy: actorUserId,
          },
          tx,
        );
        return updated;
      },
      {
        audit: {
          action: 'update',
          entity: 'me.indicator_value',
          entityId: id,
          actorUserId,
          before: existing,
        },
      },
    );
  }

  async submitValue(
    id: string,
    input: SubmitIndicatorValueInput,
    authz: UserAuthz,
    actorUserId: string,
  ) {
    const existing = await this.valueRepo.findById(id);
    if (!existing) {
      throw new NotFoundException(`Indicator value with ID '${id}' not found`);
    }

    await assertMeScope(
      authz,
      permissions.ME_VALUE_SUBMIT,
      {
        scopeType: existing.scopeType,
        scopeStateId: existing.scopeStateId,
        scopeOrgId: existing.scopeOrgId,
      },
      true,
    );

    const ind = await this.indicatorRepo.findById(existing.indicatorId);
    if (ind && ind.method === 'computed') {
      throw new ConflictProblemException({
        detail: 'Cannot manually submit values for computed indicators.',
        current: null,
        currentVersion: 0,
      });
    }

    if (existing.status !== 'draft' && existing.status !== 'returned') {
      throw new ConflictProblemException({
        detail: `Cannot submit indicator value in '${existing.status}' status (expected 'draft' or 'returned')`,
        current: existing,
        currentVersion: existing.version,
      });
    }

    const expectedVersion = input.version ?? existing.version;
    if (existing.version !== expectedVersion) {
      throw new ConflictProblemException({
        detail: 'Indicator value version mismatch',
        current: existing,
        currentVersion: existing.version,
      });
    }

    return runInTransaction(
      async (tx) => {
        const updated = await this.valueRepo.update(
          id,
          expectedVersion,
          {
            status: 'submitted',
            submittedBy: actorUserId,
            submittedAt: new Date().toISOString(),
            returnedBy: null,
            returnedAt: null,
            returnComment: null,
            updatedBy: actorUserId,
          },
          tx,
        );
        return updated;
      },
      {
        audit: {
          action: 'update',
          entity: 'me.indicator_value',
          entityId: id,
          actorUserId,
          before: existing,
        },
      },
    );
  }

  async approveValue(
    id: string,
    input: ApproveIndicatorValueInput,
    authz: UserAuthz,
    actorUserId: string,
  ) {
    const existing = await this.valueRepo.findById(id);
    if (!existing) {
      throw new NotFoundException(`Indicator value with ID '${id}' not found`);
    }

    // Approver must hold ME_VALUE_APPROVE for that scope
    await assertMeScope(
      authz,
      permissions.ME_VALUE_APPROVE,
      {
        scopeType: existing.scopeType,
        scopeStateId: existing.scopeStateId,
        scopeOrgId: existing.scopeOrgId,
      },
      true,
    );

    if (existing.status !== 'submitted') {
      throw new ConflictProblemException({
        detail: `Cannot approve indicator value in '${existing.status}' status (expected 'submitted')`,
        current: existing,
        currentVersion: existing.version,
      });
    }

    // Separation of duties: no self-approval (403)
    if (existing.submittedBy && existing.submittedBy === actorUserId) {
      throw new ForbiddenException(
        'Self-approval is forbidden. A user cannot approve their own submission.',
      );
    }

    const expectedVersion = input.version ?? existing.version;
    if (existing.version !== expectedVersion) {
      throw new ConflictProblemException({
        detail: 'Indicator value version mismatch',
        current: existing,
        currentVersion: existing.version,
      });
    }

    return runInTransaction(
      async (tx) => {
        const updated = await this.valueRepo.update(
          id,
          expectedVersion,
          {
            status: 'approved',
            approvedBy: actorUserId,
            approvedAt: new Date().toISOString(),
            updatedBy: actorUserId,
          },
          tx,
        );
        return updated;
      },
      {
        audit: {
          action: 'approve',
          entity: 'me.indicator_value',
          entityId: id,
          actorUserId,
          before: existing,
        },
      },
    );
  }

  async returnValue(
    id: string,
    input: ReturnIndicatorValueInput,
    authz: UserAuthz,
    actorUserId: string,
  ) {
    const existing = await this.valueRepo.findById(id);
    if (!existing) {
      throw new NotFoundException(`Indicator value with ID '${id}' not found`);
    }

    // Reviewer must hold ME_VALUE_APPROVE for that scope
    await assertMeScope(
      authz,
      permissions.ME_VALUE_APPROVE,
      {
        scopeType: existing.scopeType,
        scopeStateId: existing.scopeStateId,
        scopeOrgId: existing.scopeOrgId,
      },
      true,
    );

    if (existing.status !== 'submitted') {
      throw new ConflictProblemException({
        detail: `Cannot return indicator value in '${existing.status}' status (expected 'submitted')`,
        current: existing,
        currentVersion: existing.version,
      });
    }

    // Return requires comment
    if (!input.comment || input.comment.trim().length === 0) {
      throw new BadRequestException('A comment is required when returning an indicator value.');
    }

    const expectedVersion = input.version ?? existing.version;
    if (existing.version !== expectedVersion) {
      throw new ConflictProblemException({
        detail: 'Indicator value version mismatch',
        current: existing,
        currentVersion: existing.version,
      });
    }

    return runInTransaction(
      async (tx) => {
        const updated = await this.valueRepo.update(
          id,
          expectedVersion,
          {
            status: 'returned',
            returnedBy: actorUserId,
            returnedAt: new Date().toISOString(),
            returnComment: input.comment.trim(),
            updatedBy: actorUserId,
          },
          tx,
        );
        return updated;
      },
      {
        audit: {
          action: 'return',
          entity: 'me.indicator_value',
          entityId: id,
          actorUserId,
          before: existing,
        },
      },
    );
  }

  async attachEvidence(
    valueId: string,
    input: AttachEvidenceInput,
    authz: UserAuthz,
    actorUserId: string,
  ) {
    const existing = await this.valueRepo.findById(valueId);
    if (!existing) {
      throw new NotFoundException(`Indicator value with ID '${valueId}' not found`);
    }

    await assertMeScope(
      authz,
      permissions.ME_VALUE_SUBMIT,
      {
        scopeType: existing.scopeType,
        scopeStateId: existing.scopeStateId,
        scopeOrgId: existing.scopeOrgId,
      },
      true,
    );

    const f = await this.fileRepo.findById(input.fileId);
    if (!f) {
      throw new NotFoundException(`File with ID '${input.fileId}' not found`);
    }

    return runInTransaction(
      async (tx) => {
        await this.valueRepo.attachEvidence(valueId, input.fileId, tx);
        return { indicatorValueId: valueId, fileId: input.fileId };
      },
      {
        audit: {
          action: 'update',
          entity: 'me.indicator_value',
          entityId: valueId,
          actorUserId,
        },
      },
    );
  }

  async removeEvidence(valueId: string, fileId: string, authz: UserAuthz, actorUserId: string) {
    const existing = await this.valueRepo.findById(valueId);
    if (!existing) {
      throw new NotFoundException(`Indicator value with ID '${valueId}' not found`);
    }

    await assertMeScope(
      authz,
      permissions.ME_VALUE_SUBMIT,
      {
        scopeType: existing.scopeType,
        scopeStateId: existing.scopeStateId,
        scopeOrgId: existing.scopeOrgId,
      },
      true,
    );

    return runInTransaction(
      async (tx) => {
        await this.valueRepo.removeEvidence(valueId, fileId, tx);
        return { success: true };
      },
      {
        audit: {
          action: 'update',
          entity: 'me.indicator_value',
          entityId: valueId,
          actorUserId,
        },
      },
    );
  }

  async listEvidence(valueId: string, authz: UserAuthz) {
    const existing = await this.valueRepo.findById(valueId);
    if (!existing) {
      throw new NotFoundException(`Indicator value with ID '${valueId}' not found`);
    }

    await assertMeScope(
      authz,
      permissions.ME_INDICATOR_READ,
      {
        scopeType: existing.scopeType,
        scopeStateId: existing.scopeStateId,
        scopeOrgId: existing.scopeOrgId,
      },
      true,
    );

    return this.valueRepo.listEvidence(valueId);
  }
}
